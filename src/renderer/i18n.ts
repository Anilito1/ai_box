const query = new URLSearchParams(location.search);
const requested = query.get('lang');
/** Fixed for the page's life: the main process reloads the page in the new language. */
export const LANG: Lang = isLang(requested) ? requested : 'en';
export const PLATFORM = query.get('platform') ?? '';

export const { t, tn } = translator<Key>({ en, fr }, () => LANG);

/** Fills the static text of index.html: `data-i18n` sets the text, `data-i18n-title` the tooltip. */
export function translateDom(root: ParentNode = document): void {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) el.textContent = t(el.dataset.i18n as Key);
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle as Key);
    el.setAttribute('aria-label', el.title);
  }
}
